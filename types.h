//types.h

typedef unsigned char  u8;                  // Defines u8 as an unsigned 8-bit data type (0 to 255)
typedef unsigned short u16;                 // Defines u16 as an unsigned 16-bit data type (0 to 65535)
typedef unsigned int   u32;                 // Defines u32 as an unsigned 32-bit data type
typedef signed char s8;                     // Defines s8 as a signed 8-bit data type (-128 to 127)
typedef signed int s32;                     // Defines s32 as a signed 32-bit data type
typedef float f32;                          // Defines f32 as a floating-point data type

